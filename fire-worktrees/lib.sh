#!/usr/bin/env bash
#ddev-generated
# Shared functions for the fire-worktree-* host commands. Sourced, never run.
# Keep this file compatible with Bash 3.2, the macOS default, and avoid jq, yq
# and Python so the commands work on any machine that runs DDEV.

FW_CONFIG_NAME=config.worktree.local.yaml
FW_LOG_NAME=fire-worktree-start.log
FW_MARKER='# Generated by ddev fire-worktree-start. Rerun that command instead of editing.'
FW_SEED_PREFIX=fire-worktree-seed
FW_LOCK="${TMPDIR:-/tmp}"
FW_LOCK="${FW_LOCK%/}/ddev-fire-worktrees.lock"

fw::die() {
  printf '%s\n' "$*" >&2
  exit 1
}

fw::warn() {
  printf 'Warning: %s\n' "$*" >&2
}

# fw::is_legacy_marker LINE: true for the first line of a config file written by
# the project-local worktree commands this add-on replaces.
fw::is_legacy_marker() {
  case $1 in
    '# Generated by ddev worktree-start.' | '# Generated by ddev worktree-prepare.' | '# Generated by devops/scripts/worktree-setup.')
      return 0
      ;;
  esac
  return 1
}

# fw::first_line FILE
fw::first_line() {
  local line=
  IFS= read -r line <"$1" || true
  printf '%s' "$line"
}

# fw::is_generated FILE: true when this add-on or a command it replaces wrote FILE.
fw::is_generated() {
  local first
  [[ -f "$1" && ! -L "$1" ]] || return 1
  first=$(fw::first_line "$1")
  [[ "$first" == "$FW_MARKER" ]] || fw::is_legacy_marker "$first"
}

# fw::context DIR: describe the Git checkout that contains DIR. Sets FW_ROOT,
# FW_GIT_DIR, FW_COMMON_DIR, FW_PRIMARY_ROOT (empty for a bare repository) and
# FW_IS_PRIMARY.
fw::context() {
  local top
  top=$(cd "$1" && git rev-parse --show-toplevel 2>/dev/null) || fw::die "$1 is not inside a Git checkout."
  FW_ROOT=$(cd "$top" && pwd -P)
  FW_GIT_DIR=$(cd "$FW_ROOT" && cd "$(git rev-parse --git-dir)" && pwd -P)
  FW_COMMON_DIR=$(cd "$FW_ROOT" && cd "$(git rev-parse --git-common-dir)" && pwd -P)
  FW_PRIMARY_ROOT=
  if [[ "$(basename "$FW_COMMON_DIR")" == .git ]]; then
    FW_PRIMARY_ROOT=$(dirname "$FW_COMMON_DIR")
  fi
  FW_IS_PRIMARY=false
  if [[ "$FW_GIT_DIR" == "$FW_COMMON_DIR" ]]; then
    FW_IS_PRIMARY=true
  fi
  [[ -f "$FW_ROOT/.ddev/config.yaml" ]] || fw::die "$FW_ROOT has no .ddev/config.yaml."
}

# YAML readers. They understand the subset DDEV writes: top-level scalars, one
# level of nesting, and block (- item) or flow ([a, b]) lists.
FW_AWK_CLEAN='
  function clean(s) {
    sub(/[ \t]+#.*$/, "", s)
    gsub(/^[ \t]+|[ \t]+$/, "", s)
    if (s ~ /^".*"$/ || s ~ /^\047.*\047$/) s = substr(s, 2, length(s) - 2)
    return s
  }'

# fw::yaml_scalar FILE KEY
fw::yaml_scalar() {
  awk -v key="$2" "$FW_AWK_CLEAN"'
    index($0, key ":") == 1 {
      rest = substr($0, length(key) + 2)
      if (rest == "" || rest ~ /^[ \t]/) { print clean(rest); exit }
    }' "$1"
}

# fw::yaml_nested FILE PARENT KEY
fw::yaml_nested() {
  awk -v parent="$2" -v key="$3" "$FW_AWK_CLEAN"'
    index($0, parent ":") == 1 { inblock = 1; next }
    inblock && /^[^ \t#]/ { exit }
    inblock {
      line = $0
      sub(/^[ \t]+/, "", line)
      if (index(line, key ":") == 1) {
        rest = substr(line, length(key) + 2)
        if (rest == "" || rest ~ /^[ \t]/) { print clean(rest); exit }
      }
    }' "$1"
}

# fw::yaml_list FILE KEY: print each item of a top-level list on its own line.
fw::yaml_list() {
  awk -v key="$2" "$FW_AWK_CLEAN"'
    !inlist && index($0, key ":") == 1 {
      rest = substr($0, length(key) + 2)
      if (rest != "" && rest !~ /^[ \t]/) next
      sub(/^[ \t]+/, "", rest)
      sub(/[ \t]+#.*$/, "", rest)
      if (rest ~ /^\[/) {
        sub(/^\[/, "", rest)
        sub(/\][ \t]*$/, "", rest)
        n = split(rest, items, ",")
        for (i = 1; i <= n; i++) { v = clean(items[i]); if (v != "") print v }
        exit
      }
      inlist = 1
      next
    }
    inlist && /^[ \t]*-([ \t]|$)/ {
      v = $0
      sub(/^[ \t]*-[ \t]*/, "", v)
      v = clean(v)
      if (v != "") print v
      next
    }
    inlist && /^[ \t]*(#.*)?$/ { next }
    inlist { exit }' "$1"
}

# fw::config_files DIR: DIR's DDEV config files in DDEV's load order, without
# the files worktree commands generate.
fw::config_files() {
  local f
  printf '%s\n' "$1/.ddev/config.yaml"
  (
    # DDEV loads config.*.y*ml in Go's byte order, which C-locale globbing matches.
    LC_ALL=C
    for f in "$1"/.ddev/config.*.y*ml; do
      [[ -f "$f" ]] || continue
      fw::is_generated "$f" && continue
      printf '%s\n' "$f"
    done
  )
}

# fw::config_scalar DIR KEY: the last value any config file sets.
fw::config_scalar() {
  local f v value=
  while IFS= read -r f; do
    v=$(fw::yaml_scalar "$f" "$2")
    if [[ -n "$v" ]]; then
      value=$v
    fi
  done < <(fw::config_files "$1")
  printf '%s' "$value"
}

# fw::config_nested DIR PARENT KEY
fw::config_nested() {
  local f v value=
  while IFS= read -r f; do
    v=$(fw::yaml_nested "$f" "$2" "$3")
    if [[ -n "$v" ]]; then
      value=$v
    fi
  done < <(fw::config_files "$1")
  printf '%s' "$value"
}

# fw::config_list DIR KEY: every config file's items, in load order.
fw::config_list() {
  local f
  while IFS= read -r f; do
    fw::yaml_list "$f" "$2"
  done < <(fw::config_files "$1")
}

# fw::web_environment DIR: DIR's web_environment entries, one NAME=value per
# line. As in DDEV, a later entry for a NAME replaces an earlier one.
fw::web_environment() {
  fw::config_list "$1" web_environment | awk '
    {
      i = index($0, "=")
      if (!i) next
      name = substr($0, 1, i - 1)
      if (!(name in entry)) order[++n] = name
      entry[name] = $0
    }
    END { for (j = 1; j <= n; j++) print entry[order[j]] }'
}

# fw::setting DIR NAME DEFAULT: NAME from web_environment, where a later file
# (such as config.local.yaml) overrides an earlier one. Empty means DEFAULT.
fw::setting() {
  local item value=$3
  while IFS= read -r item; do
    if [[ "$item" == "$2="* && -n "${item#"$2="}" ]]; then
      value=${item#"$2="}
    fi
  done < <(fw::config_list "$1" web_environment)
  printf '%s' "$value"
}

# fw::slug TEXT MAX: lowercase letters, digits and single hyphens, at most MAX long.
fw::slug() {
  local s
  s=$(printf '%s' "$1" | LC_ALL=C tr '[:upper:]' '[:lower:]' | LC_ALL=C sed -e 's/[^a-z0-9]/-/g' -e 's/--*/-/g' -e 's/^-//' | cut -c "1-$2")
  printf '%s' "${s%-}"
}

# fw::project_name_of DIR: the DDEV name DIR's own config gives it. DDEV falls
# back to the directory name when config.yaml has no name.
fw::project_name_of() {
  local name
  name=$(fw::config_scalar "$1" name)
  if [[ -z "$name" ]]; then
    name=$(fw::slug "$(basename "$1")" 63)
  fi
  printf '%s' "$name"
}

# fw::primary_name: the primary checkout's DDEV project name. A config.yaml
# without name: gives each checkout a different name, so ask the primary's.
fw::primary_name() {
  local root=${FW_PRIMARY_ROOT:-$FW_ROOT}
  [[ -f "$root/.ddev/config.yaml" ]] || root=$FW_ROOT
  fw::project_name_of "$root"
}

# fw::generated_name DIR: the project name in DIR's generated config, if any.
fw::generated_name() {
  local f
  for f in "$1/.ddev/$FW_CONFIG_NAME" "$1/.ddev/config.worktree.yaml"; do
    if fw::is_generated "$f"; then
      fw::yaml_scalar "$f" name
      return 0
    fi
  done
  return 0
}

# fw::tld DIR
fw::tld() {
  local tld
  tld=$(fw::config_scalar "$1" project_tld)
  printf '%s' "${tld:-ddev.site}"
}

# fw::urls DIR NAME: the URLs of DIR's worktree project NAME, main URL first.
fw::urls() {
  local tld host
  tld=$(fw::tld "$1")
  printf 'https://%s.%s\n' "$2" "$tld"
  while IFS= read -r host; do
    if [[ -n "$host" ]]; then
      printf 'https://%s.%s\n' "$host" "$tld"
    fi
  done < <(fw::yaml_list "$1/.ddev/$FW_CONFIG_NAME" additional_hostnames)
}

# fw::primary_url_settings DIR PRIMARY: DIR's web_environment entries whose value
# names a hostname of the primary project PRIMARY. A worktree inherits them, so
# they point it at the primary site.
fw::primary_url_settings() {
  local tld host hosts re
  tld=$(fw::tld "$1")
  hosts="$2.$tld"
  while IFS= read -r host; do
    host=${host#\*.}
    # The primary name's subdomains already match.
    if [[ -n "$host" && "$host" != "$2" && "$host" != *".$2" ]]; then
      hosts="$hosts"$'\n'"$host.$tld"
    fi
  done < <(fw::config_list "$1" additional_hostnames)
  re=$(printf '%s\n' "$hosts" | sed 's/[.]/\\./g' | paste -sd '|' -)
  fw::web_environment "$1" | grep -E "=(.*[^A-Za-z0-9.-])?([A-Za-z0-9-]+\.)*($re)([^A-Za-z0-9.-]|\$)" || true
}

# fw::check_hostname HOST: DNS labels can't exceed 63 characters.
fw::check_hostname() {
  local rest=$1 label
  while [[ -n "$rest" ]]; do
    label=${rest%%.*}
    if [[ ${#label} -gt 63 ]]; then
      fw::die "Hostname $1 has a label longer than 63 characters. Shorten WORKTREE_NAME_PREFIX or the directory name."
    fi
    if [[ "$rest" == *.* ]]; then
      rest=${rest#*.}
    else
      rest=
    fi
  done
}

# fw::rewrite_hostnames DIR PRIMARY NAME: DIR's additional_hostnames for project
# NAME. <sub>.PRIMARY becomes <sub>.NAME; any other host becomes <host>.NAME.
fw::rewrite_hostnames() {
  local host new
  while IFS= read -r host; do
    [[ -n "$host" && "$host" != "$2" ]] || continue
    if [[ "$host" == *".$2" ]]; then
      new="${host%".$2"}.$3"
    else
      new="$host.$3"
    fi
    fw::check_hostname "$new"
    printf '%s\n' "$new"
  done < <(fw::config_list "$1" additional_hostnames)
}

# fw::db_volume_exists NAME: true once DDEV has created NAME's database volume.
fw::db_volume_exists() {
  docker volume ls -q 2>/dev/null | grep -Eq "^$1-(mariadb|mysql|postgres)\$"
}

# fw::running_containers: the names of running DDEV containers.
fw::running_containers() {
  docker ps --filter label=com.ddev.site-name --format '{{.Names}}' 2>/dev/null || true
}

# fw::status NAME RUNNING: running, stopped or not started, given the
# fw::running_containers output.
fw::status() {
  if printf '%s\n' "$2" | grep -qxF "ddev-$1-web"; then
    echo running
  elif fw::db_volume_exists "$1"; then
    echo stopped
  else
    echo 'not started'
  fi
}

# fw::compose_project NAME: the Docker Compose project DDEV runs NAME as.
fw::compose_project() {
  printf 'ddev-%s' "$1" | tr -d . | LC_ALL=C tr '[:upper:]' '[:lower:]'
}

# fw::project_volumes NAME: the volumes Docker Compose created for NAME, which
# include the database and add-on services such as Solr and Redis.
fw::project_volumes() {
  docker volume ls -q --filter "label=com.docker.compose.project=$(fw::compose_project "$1")" 2>/dev/null || true
}

# fw::has_environment NAME: true while DDEV knows NAME or any of its volumes remain.
fw::has_environment() {
  ddev describe "$1" >/dev/null 2>&1 || fw::db_volume_exists "$1" || [[ -n "$(fw::project_volumes "$1")" ]]
}

# fw::delete_project NAME: delete NAME's DDEV project and every volume it left.
# Once the checkout is gone, DDEV can't read the compose file that lists add-on
# services' volumes, so ddev delete leaves them.
fw::delete_project() {
  local volume
  ddev delete --omit-snapshot --yes "$1"
  while IFS= read -r volume; do
    [[ -n "$volume" ]] || continue
    if docker volume rm "$volume" >/dev/null; then
      printf 'Deleted volume %s\n' "$volume"
    else
      fw::warn "Couldn't delete volume $volume."
    fi
  done < <(fw::project_volumes "$1")
}

# fw::try_lock DIR: take the lock at DIR, clearing one left by a process that
# has exited. Fails while a running process holds it.
fw::try_lock() {
  local pid
  until mkdir "$1" 2>/dev/null; do
    pid=$(cat "$1/pid" 2>/dev/null || true)
    if [[ -n "$pid" ]] && ! kill -0 "$pid" 2>/dev/null; then
      rm -rf "$1"
      continue
    fi
    return 1
  done
  echo $$ >"$1/pid"
}

fw::lock() {
  local waited=0
  while ! fw::try_lock "$FW_LOCK"; do
    if ((waited % 30 == 0)); then
      echo 'Waiting for another worktree to finish starting...'
    fi
    if ((waited >= 1800)); then
      fw::die "Timed out waiting for $FW_LOCK. Delete it if no other worktree is starting."
    fi
    sleep 2
    waited=$((waited + 2))
  done
  trap 'rm -rf "$FW_LOCK"' EXIT
}

fw::unlock() {
  rm -rf "$FW_LOCK"
  trap - EXIT
}

# fw::confirm YES: ask before deleting data, unless YES is true. Exits unless
# the answer is yes, and when no one is at the terminal to answer.
fw::confirm() {
  local answer
  if [[ "$1" == true ]]; then
    return 0
  fi
  [[ -t 0 ]] || fw::die 'Pass --yes to confirm when not running interactively.'
  read -r -p 'Continue? [y/N] ' answer || answer=
  if [[ "$answer" != [yY] && "$answer" != [yY][eE][sS] ]]; then
    echo 'Cancelled.'
    exit 1
  fi
}

# Registry of worktrees this repository started, kept in the shared .git
# directory so it outlives removed checkouts. One "<name><TAB><path>" per line.
fw::registry_file() {
  printf '%s/fire-worktrees' "$FW_COMMON_DIR"
}

# Registry changes take a lock of their own, so parallel starts, removes and
# prunes keep each other's entries. It's held for moments, unlike the start lock
# that's held through ddev start. Take it only while not holding the start lock,
# since each sets the EXIT trap.
fw::with_registry_lock() {
  local lock waited=0 status=0
  lock="$(fw::registry_file).lock"
  while ! fw::try_lock "$lock"; do
    if ((waited >= 300)); then
      fw::die "Timed out waiting for $lock. Delete it if no other fire-worktree command is running."
    fi
    sleep 0.1
    waited=$((waited + 1))
  done
  # shellcheck disable=SC2064 # Expand now; lock is local.
  trap "rm -rf $(printf '%q' "$lock")" EXIT
  "$@" || status=$?
  rm -rf "$lock"
  trap - EXIT
  return "$status"
}

# fw::registry_drop NAME: remove NAME's entry. Hold the registry lock.
fw::registry_drop() {
  local file tmp
  file=$(fw::registry_file)
  [[ -f "$file" ]] || return 0
  tmp="$file.$$"
  awk -F '\t' -v name="$1" '$1 != name' "$file" >"$tmp" && mv "$tmp" "$file"
}

# fw::registry_put NAME PATH: record NAME at PATH. Hold the registry lock.
fw::registry_put() {
  fw::registry_drop "$1" &&
    printf '%s\t%s\n' "$1" "$2" >>"$(fw::registry_file)"
}

fw::registry_remove() {
  fw::with_registry_lock fw::registry_drop "$1"
}

fw::registry_add() {
  fw::with_registry_lock fw::registry_put "$1" "$2"
}

# fw::exclude_generated: exclude the files startup writes in a worktree from
# Git. Hold the registry lock, so parallel starts add each line once.
fw::exclude_generated() {
  local f exclude="$FW_COMMON_DIR/info/exclude"
  # DDEV gitignores config.*.local.yaml once it writes .ddev/.gitignore, but
  # nothing ignores the log. Exclude both, so a worktree's status stays clean.
  mkdir -p "$FW_COMMON_DIR/info" || return 1
  for f in "$FW_CONFIG_NAME" "$FW_LOG_NAME"; do
    if ! grep -qxF "/.ddev/$f" "$exclude" 2>/dev/null; then
      printf '/.ddev/%s\n' "$f" >>"$exclude" || return 1
    fi
  done
}

# fw::default_ref: the remote's default branch, as a local branch when one exists.
fw::default_ref() {
  local ref
  ref=$(git -C "$FW_ROOT" symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null || true)
  ref=${ref#origin/}
  ref=${ref:-main}
  if ! git -C "$FW_ROOT" show-ref --verify --quiet "refs/heads/$ref" &&
    git -C "$FW_ROOT" show-ref --verify --quiet "refs/remotes/origin/$ref"; then
    ref="origin/$ref"
  fi
  printf '%s' "$ref"
}

# fw::checked_out_at BRANCH: the worktree that has BRANCH checked out, if any.
fw::checked_out_at() {
  git -C "$FW_ROOT" worktree list --porcelain | awk -v ref="branch refs/heads/$1" '
    index($0, "worktree ") == 1 { path = substr($0, 10) }
    $0 == ref && !found { print path; found = 1 }'
}

# fw::pr_info NUMBER: look up pull request NUMBER on origin with gh. Sets
# FW_PR_HEAD and FW_PR_BASE to its head and base branches, FW_PR_FORK to true
# when its head branch is in a fork, and FW_PR_OWNER to the head's owner. Fails
# without gh.
fw::pr_info() {
  local url info
  FW_PR_HEAD=''
  FW_PR_BASE=''
  FW_PR_FORK=''
  FW_PR_OWNER=''
  command -v gh >/dev/null 2>&1 || return 1
  url=$(git -C "$FW_ROOT" remote get-url origin) || return 1
  info=$(gh pr view "$1" --repo "$url" --json headRefName,baseRefName,isCrossRepository,headRepositoryOwner \
    --jq '.headRefName, .baseRefName, .isCrossRepository, (.headRepositoryOwner.login // "")') || return 1
  # shellcheck disable=SC2034 # fire-worktree-create reads FW_PR_FORK and FW_PR_OWNER.
  { IFS= read -r FW_PR_HEAD && IFS= read -r FW_PR_BASE && IFS= read -r FW_PR_FORK && IFS= read -r FW_PR_OWNER; } <<<"$info" || return 1
  [[ -n "$FW_PR_HEAD" && -n "$FW_PR_BASE" ]]
}

# fw::seed_snapshot MODE: print the snapshot file to seed a new database from,
# or nothing for a fresh database.
fw::seed_snapshot() {
  local mode=$1 dir primary snap f newest='' other='' type version
  case $mode in
    fresh)
      return 0
      ;;
    primary | latest)
      [[ -n "$FW_PRIMARY_ROOT" && -f "$FW_PRIMARY_ROOT/.ddev/config.yaml" ]] ||
        fw::die "No primary checkout with a DDEV project to copy the database from. Use --db=fresh."
      dir="$FW_PRIMARY_ROOT/.ddev/db_snapshots"
      if [[ "$mode" == primary ]]; then
        primary=$(fw::primary_name)
        snap="$FW_SEED_PREFIX-$(date +%Y%m%d%H%M%S)"
        echo "Snapshotting the $primary database to copy it into this worktree..." >&2
        if ddev snapshot "$primary" --name="$snap" >&2; then
          for f in "$dir/$snap"-*; do
            [[ -f "$f" ]] && newest=$f
          done
          # Keep only the newest seed snapshot.
          for f in "$dir/$FW_SEED_PREFIX"-*; do
            if [[ -f "$f" && "$f" != "$newest" ]]; then
              rm -f "$f"
            fi
          done
        else
          fw::warn "Couldn't snapshot $primary. Start it with 'ddev start' in $FW_PRIMARY_ROOT to copy its current data."
        fi
      fi
      if [[ -z "$newest" ]]; then
        # The newest seed snapshot that matches this worktree's database server,
        # else the newest other snapshot that does, such as one taken by hand.
        type=$(fw::config_nested "$FW_ROOT" database type)
        version=$(fw::config_nested "$FW_ROOT" database version)
        while IFS= read -r f; do
          [[ -f "$dir/$f" ]] || continue
          if [[ -n "$type" && -n "$version" && "$f" != *"-${type}_${version}."* ]]; then
            continue
          fi
          if [[ "$f" == "$FW_SEED_PREFIX"-* ]]; then
            newest="$dir/$f"
            break
          fi
          other=${other:-"$dir/$f"}
        done < <(ls -t "$dir" 2>/dev/null)
        if [[ -z "$newest" && -z "$other" ]]; then
          fw::die "The primary checkout has no database snapshot to copy. Start its project, or use --db=fresh."
        fi
        if [[ "$mode" == primary ]]; then
          fw::warn "Using the older snapshot $(basename "${newest:-$other}") instead."
        elif [[ -z "$newest" ]]; then
          fw::warn "No earlier worktree copy to reuse, so using the snapshot $(basename "$other"). Use --db=primary for a new copy, or --db=<file> to choose one."
        fi
        newest=${newest:-$other}
      fi
      printf '%s' "$newest"
      ;;
    *)
      [[ -f "$mode" ]] || fw::die "--db must be primary, latest, fresh, a snapshot or a SQL dump; got $mode."
      printf '%s/%s' "$(cd "$(dirname "$mode")" && pwd -P)" "$(basename "$mode")"
      ;;
  esac
}

# fw::db_arg VALUE: a --db value with any file path made absolute, so it still
# points at the same file after the commands change directory.
fw::db_arg() {
  case $1 in
    '' | primary | latest | fresh) printf '%s' "$1" ;;
    *)
      [[ -f "$1" ]] || fw::die "--db must be primary, latest, fresh, a snapshot or a SQL dump; got $1."
      printf '%s/%s' "$(cd "$(dirname "$1")" && pwd -P)" "$(basename "$1")"
      ;;
  esac
}

# fw::db_record_file: where startup notes the source of FW_ROOT's database. It
# lives in the worktree's own Git directory, which Git deletes with the worktree.
fw::db_record_file() {
  printf '%s/fire-worktree-db' "$FW_GIT_DIR"
}

# fw::record_db MODE FILE: note that FW_ROOT's new database comes from --db=MODE,
# using FILE, the snapshot or dump.
fw::record_db() {
  local source=$1
  case $source in
    primary | latest | fresh) ;;
    *) if fw::is_dump "$2"; then source=dump; else source=snapshot; fi ;;
  esac
  printf '%s\t%s\n' "$source" "$2" >"$(fw::db_record_file)"
}

# fw::db_source: FW_ROOT's database source and file, tab-separated. The source
# is primary, latest, fresh, snapshot, dump, or unknown for a database created
# before startup recorded it.
fw::db_source() {
  local source='' file=''
  if [[ -f "$(fw::db_record_file)" ]]; then
    IFS=$'\t' read -r source file <"$(fw::db_record_file)" || true
  fi
  printf '%s\t%s' "${source:-unknown}" "$file"
}

# fw::db_created [DATE ARGS]: when FW_ROOT's database was created, formatted by
# date, or nothing for a database created before startup recorded its source.
# fw::record_db rewrites the record with each new database, so it's the record's
# modification time.
fw::db_created() {
  local file
  file=$(fw::db_record_file)
  [[ -f "$file" ]] || return 0
  date -r "$file" "$@"
}

# fw::is_dump FILE: true for a file ddev import-db reads, such as FIRE's
# reference/site-db.sql.gz, rather than a ddev snapshot.
fw::is_dump() {
  case $1 in
    *.sql | *.sql.gz | *.sql.bz2 | *.sql.xz | *.mysql | *.mysql.gz | *.zip | *.tgz | *.tar.gz) return 0 ;;
  esac
  return 1
}

# fw::has_site_build DIR: true when DIR has ddev-fire's site-build command and
# DDEV offers it for DIR's project type.
fw::has_site_build() {
  local file="$1/.ddev/commands/host/site-build" types
  [[ -f "$file" && -f "$1/.ddev/fire/scripts/lib.sh" ]] || return 1
  types=$(sed -n 's/^## ProjectTypes:[[:space:]]*//p' "$file" | tr -d ' \t\r')
  [[ -z "$types" || ",$types," == *",$(fw::config_scalar "$1" type),"* ]]
}

# fw::build_command DIR: the command that finishes a worktree after its database
# is copied in, or "none".
fw::build_command() {
  local cmd
  cmd=$(fw::setting "$1" WORKTREE_BUILD_COMMAND "")
  if [[ -z "$cmd" ]]; then
    # --skip-db-import also skips the database download.
    if fw::has_site_build "$1"; then
      cmd='ddev site-build --skip-db-import'
    else
      case $(fw::config_scalar "$1" type) in
        # drush deploy needs Drupal 8.8 or later.
        drupal6 | drupal7) cmd='ddev drush updb -y' ;;
        drupal*) cmd='ddev drush deploy -y' ;;
        *) cmd=none ;;
      esac
    fi
  fi
  printf '%s' "$cmd"
}

# fw::is_drupal DIR: true for DDEV's Drupal project types.
fw::is_drupal() {
  [[ "$(fw::config_scalar "$1" type)" == drupal* ]]
}

# fw::login_link URL: a one-time login link to the Drupal site at URL. Run it in
# the worktree while its project is running. --uri overrides a DRUSH_OPTIONS_URI
# the worktree inherited from the primary checkout.
fw::login_link() {
  local link
  link=$(ddev drush uli --no-browser --uri="$1" 2>/dev/null | tr -d '\r' | grep -E '^https?://' | tail -n 1) || true
  [[ -n "$link" ]] || return 1
  printf '%s' "$link"
}

# fw::json TEXT: TEXT as a JSON string, or null when it's empty.
fw::json() {
  local s=$1 bs=\\ q=\"
  if [[ -z "$s" ]]; then
    printf null
    return 0
  fi
  s=${s//"$bs"/"$bs$bs"}
  s=${s//"$q"/"$bs$q"}
  s=${s//$'\t'/"${bs}t"}
  s=${s//$'\n'/"${bs}n"}
  s=${s//$'\r'/"${bs}r"}
  printf '"%s"' "$s"
}

# fw::populate_hint DIR: how to fill an empty database.
fw::populate_hint() {
  if fw::has_site_build "$1"; then
    echo 'ddev site-build'
  elif [[ -f "$1/fire.yml" ]]; then
    echo 'fire build'
  else
    echo 'ddev import-db --file=<dump>, or ddev pull <provider>'
  fi
}

# fw::build_failure DIR: what startup does when the build fails. fail exits 1;
# warn exits 0, so an agent tool carries on in the running site.
fw::build_failure() {
  local mode
  mode=$(fw::setting "$1" WORKTREE_BUILD_FAILURE fail)
  case $mode in
    fail | warn) printf '%s' "$mode" ;;
    *) fw::die "WORKTREE_BUILD_FAILURE must be fail or warn; got $mode." ;;
  esac
}

# fw::copy_list: FW_ROOT's WORKTREE_COPY_FILES.
fw::copy_list() {
  local docroot
  docroot=$(fw::config_scalar "$FW_ROOT" docroot)
  fw::setting "$FW_ROOT" WORKTREE_COPY_FILES ".ddev/config.local.yaml ${docroot:+$docroot/}sites/default/settings.local.php"
}

# fw::copy_files SOURCE: copy gitignored local files that FW_ROOT lacks.
fw::copy_files() {
  local rel seen=' ' more=true
  local -a files
  [[ -d "$1" && "$1" != "$FW_ROOT" ]] || return 0
  # A copied config.local.yaml can change the list, so read it again after
  # each pass that copies something.
  while [[ "$more" == true ]]; do
    more=false
    read -r -a files <<<"$(fw::copy_list)"
    for rel in ${files[@]+"${files[@]}"}; do
      [[ "$seen" != *" $rel "* ]] || continue
      seen="$seen$rel "
      case $rel in
        /* | *..*)
          fw::warn "Skipping $rel in WORKTREE_COPY_FILES; use a path inside the project."
          continue
          ;;
      esac
      if [[ -f "$1/$rel" && ! -e "$FW_ROOT/$rel" && ! -L "$FW_ROOT/$rel" ]]; then
        mkdir -p "$(dirname "$FW_ROOT/$rel")"
        cp "$1/$rel" "$FW_ROOT/$rel"
        printf 'Copied %s\n' "$rel"
        more=true
      fi
    done
  done
}

# fw::write_config PRIMARY: write FW_ROOT's generated DDEV config for FW_NAME.
fw::write_config() {
  local cfg="$FW_ROOT/.ddev/$FW_CONFIG_NAME" hosts key fqdns
  hosts=$(fw::rewrite_hostnames "$FW_ROOT" "$1" "$FW_NAME") || exit 1
  fqdns=$(fw::config_list "$FW_ROOT" additional_fqdns | tr '\n' ' ')
  {
    printf '%s\n' "$FW_MARKER"
    # Replace rather than merge these keys, so this project never claims the
    # primary checkout's hostnames or host ports.
    printf 'override_config: true\nname: %s\n' "$FW_NAME"
    if [[ -n "$hosts" ]]; then
      printf 'additional_hostnames:\n'
      printf '%s\n' "$hosts" | sed 's/^/  - /'
    else
      printf 'additional_hostnames: []\n'
    fi
    printf 'additional_fqdns: []\n'
    for key in host_https_port host_webserver_port host_db_port host_mailpit_port host_xhgui_port; do
      if [[ -n "$(fw::config_scalar "$FW_ROOT" "$key")" ]]; then
        printf '%s: ""\n' "$key"
      fi
    done
  } >"$cfg.tmp"
  mv "$cfg.tmp" "$cfg"
  if [[ -n "${fqdns// /}" ]]; then
    echo "Left out additional_fqdns (${fqdns% }); two running projects can't share them."
  fi
}

# fw::import_dump FILE: import the SQL dump FILE, if any, into FW_ROOT's new
# database once its project is running.
fw::import_dump() {
  [[ -n "$1" ]] || return 0
  printf 'Importing %s into the new database\n' "$1"
  ddev import-db --file="$1" ||
    fw::die "The worktree is running, but the import failed. Fix the error, then run: ddev import-db --file=$1"
}

# fw::build_after_copy BUILD: run FW_ROOT's build command so a copied database
# matches the branch, or with BUILD false, print it. Fails when the build fails.
fw::build_after_copy() {
  local cmd status=0
  cmd=$(fw::build_command "$FW_ROOT")
  if [[ "$1" == true && "$cmd" != none ]]; then
    printf '\nBuilding with: %s\n' "$cmd"
    bash -c "$cmd" || status=1
  elif [[ "$cmd" != none ]]; then
    printf '\nSkipped the build. To run it: %s\n' "$cmd"
  fi
  if [[ -f "$FW_ROOT/fire.yml" && "$cmd" == 'ddev drush '* && -z "$(fw::setting "$FW_ROOT" WORKTREE_BUILD_COMMAND "")" ]]; then
    printf "This project uses FIRE, and drush deploy doesn't build its theme. To build everything\n"
    printf 'after each copy, set WORKTREE_BUILD_COMMAND=fire build --no-db-import (see the add-on README).\n'
  fi
  return "$status"
}

# fw::build_failed MODE: report FW_ROOT's failed build, once its URLs are
# printed. With MODE fail it exits 1; with warn it returns, so an agent tool
# carries on in the running site.
fw::build_failed() {
  local cmd
  cmd=$(fw::build_command "$FW_ROOT")
  if [[ "$1" == warn ]]; then
    fw::warn "The worktree is running, but the build failed. Fix the error, then run: $cmd"
    if [[ -n "${FW_START_LOG:-}" ]]; then
      printf 'Startup log: %s\n' "$FW_START_LOG" >&2
    fi
  else
    fw::die "The worktree is running, but the build failed. Fix the error, then run: $cmd"
  fi
}

# fw::show_worktree EMPTY: print FW_NAME's URLs, then how to fill its database
# when EMPTY is true, else a one-time login link for a Drupal site.
fw::show_worktree() {
  local url link
  printf '\nWorktree URLs:\n'
  fw::urls "$FW_ROOT" "$FW_NAME" | sed 's/^/  /'
  if [[ "$1" == true ]]; then
    printf 'To populate the database: %s\n' "$(fw::populate_hint "$FW_ROOT")"
  elif fw::is_drupal "$FW_ROOT"; then
    url="https://$FW_NAME.$(fw::tld "$FW_ROOT")"
    if link=$(fw::login_link "$url"); then
      printf 'One-time login link: %s\n' "$link"
    else
      fw::warn "Couldn't create a login link. Try: ddev drush uli --uri=$url"
    fi
  fi
}

# fw::start_worktree DIR DB BUILD: configure, start and build the linked worktree
# that contains DIR, appending the output to its start log. DB is primary,
# latest, fresh or a snapshot file; empty means the WORKTREE_DB setting. BUILD
# is true or false.
fw::start_worktree() {
  local status pipefail=false
  fw::context "$1"
  if [[ "$FW_IS_PRIMARY" == true ]]; then
    fw::die 'Run fire-worktree-start in a linked Git worktree, not the primary checkout.'
  fi
  cd "$FW_ROOT" || exit 1
  fw::with_registry_lock fw::exclude_generated || exit 1
  # Agent tools often show only a setup script's exit status, so keep every
  # start's output where whoever opens the worktree can read it.
  FW_START_LOG="$FW_ROOT/.ddev/$FW_LOG_NAME"
  printf '=== %s: fire-worktree-start\n' "$(date '+%Y-%m-%d %H:%M:%S')" >>"$FW_START_LOG"
  # Read the steps' status from PIPESTATUS rather than testing the pipeline with
  # if or ||, which would turn off set -e inside the steps. Turn off pipefail
  # meanwhile, so a failure doesn't end this shell before it names the log.
  if [[ -o pipefail ]]; then
    pipefail=true
    set +o pipefail
  fi
  fw::start_steps "$2" "$3" 2>&1 | tee -a "$FW_START_LOG"
  status=${PIPESTATUS[0]}
  if [[ "$pipefail" == true ]]; then
    set -o pipefail
  fi
  if [[ "$status" != 0 ]]; then
    printf 'Startup log: %s\n' "$FW_START_LOG" >&2
  fi
  return "$status"
}

# fw::start_steps DB BUILD: fw::start_worktree's work, in FW_ROOT.
fw::start_steps() {
  local db=$1 build=$2 primary cfg legacy source prefix dir slug suffix f seed='' dump='' item nested=false composer_root new_db=false empty=false on_failure build_failed=false
  cfg=".ddev/$FW_CONFIG_NAME"
  legacy=.ddev/config.worktree.yaml
  if [[ (-e "$cfg" || -L "$cfg") ]] && ! fw::is_generated "$cfg"; then
    fw::die "Refusing to overwrite $cfg; this add-on didn't write it."
  fi
  if [[ -e "$legacy" ]] && ! fw::is_generated "$legacy" && [[ -n "$(fw::yaml_scalar "$legacy" name)" ]]; then
    fw::die "$legacy sets name: and loads after $cfg. Remove it or its name: line."
  fi
  (
    LC_ALL=C
    for f in .ddev/config.*.y*ml; do
      [[ -f "$f" && "$(basename "$f")" > "$FW_CONFIG_NAME" ]] || continue
      fw::is_generated "$f" && continue
      if [[ -n "$(fw::yaml_scalar "$f" name)" ]]; then
        fw::die "$f sets name: and loads after $cfg, so it would override this worktree's project name."
      fi
    done
  ) || exit 1

  # Copy local files first, so a copied config.local.yaml sets the name and
  # hostnames. Creation names its source checkout. Otherwise use T3's hint, then
  # the primary.
  source=${WORKTREE_SOURCE_ROOT:-${T3CODE_PROJECT_ROOT:-$FW_PRIMARY_ROOT}}
  fw::copy_files "$source"

  # Reuse the name of an existing environment, including ones the replaced
  # project-local commands created, so the worktree keeps its database.
  FW_NAME=$(fw::generated_name "$FW_ROOT")
  primary=$(fw::primary_name)
  if [[ -z "$FW_NAME" ]]; then
    # Path-based names stay stable across branch renames and tell apart
    # worktrees whose directory names match.
    prefix=$(fw::slug "$(fw::setting "$FW_ROOT" WORKTREE_NAME_PREFIX "$primary")" 12)
    dir=$(basename "$FW_ROOT")
    if [[ -n "$FW_PRIMARY_ROOT" ]]; then
      dir=${dir#"$(basename "$FW_PRIMARY_ROOT")-"}
    fi
    slug=$(fw::slug "$dir" 24)
    suffix=$(printf '%s' "$FW_ROOT" | cksum | awk '{print $1}')
    FW_NAME="${prefix:-wt}-${slug:-wt}-$suffix"
  fi
  if [[ "$FW_NAME" == "$primary" ]]; then
    fw::die "Refusing to give this worktree the primary project's name, $primary."
  fi
  fw::write_config "$primary"
  if fw::is_generated "$legacy"; then
    rm -f "$legacy"
  fi
  fw::registry_add "$FW_NAME" "$FW_ROOT" || exit 1
  printf 'Configured DDEV project %s\n' "$FW_NAME"
  while IFS= read -r item; do
    [[ -n "$item" ]] || continue
    fw::warn "This worktree inherits $item from web_environment, which points it at the primary site. Build the value from \${DDEV_SITENAME}.\${DDEV_TLD} or \$DDEV_PRIMARY_URL instead."
  done < <(fw::primary_url_settings "$FW_ROOT" "$primary")

  if [[ -n "$FW_PRIMARY_ROOT" && "$FW_ROOT" == "$FW_PRIMARY_ROOT"/* ]]; then
    nested=true
    fw::warn "This worktree is inside the primary checkout. If the primary project uses Mutagen, it syncs this whole worktree into its own container."
  fi

  db=${db:-$(fw::setting "$FW_ROOT" WORKTREE_DB primary)}
  on_failure=$(fw::build_failure "$FW_ROOT")
  fw::lock
  if ! fw::db_volume_exists "$FW_NAME"; then
    new_db=true
    seed=$(fw::seed_snapshot "$db")
  fi
  # DDEV seeds only from snapshots; a SQL dump is imported once it's running.
  if [[ -n "$seed" ]] && fw::is_dump "$seed"; then
    dump=$seed
    seed=
  fi
  if [[ "$new_db" == true ]]; then
    fw::record_db "$db" "${seed:-$dump}"
  fi
  if [[ -n "$seed" ]]; then
    printf 'Seeding the new database from %s\n' "$seed"
  fi
  if [[ "$nested" == true ]]; then
    # DDEV asks whether to use an unregistered nested project, defaulting to the
    # project around it. Answer yes; starting registers it for later commands.
    DDEV_NONINTERACTIVE=false ddev start ${seed:+"--seed-snapshot=$seed"} <<<y || fw::die 'ddev start failed.'
  else
    ddev start ${seed:+"--seed-snapshot=$seed"} || fw::die 'ddev start failed.'
  fi
  fw::unlock
  fw::import_dump "$dump"

  composer_root=$(fw::config_scalar "$FW_ROOT" composer_root)
  if [[ -f "${composer_root:-.}/composer.json" ]]; then
    ddev composer install || fw::die 'ddev composer install failed.'
  fi

  if [[ -n "$seed" || -n "$dump" ]]; then
    fw::build_after_copy "$build" || build_failed=true
  elif [[ "$new_db" == true ]]; then
    empty=true
  fi
  fw::show_worktree "$empty"
  if [[ "$build_failed" == true ]]; then
    fw::build_failed "$on_failure"
  fi
}

# fw::refresh_worktree DIR DB BUILD YES: replace the database of the started
# worktree that contains DIR with a new one from DB, as a first start would, and
# keep its project and other volumes. Asks first unless YES is true.
fw::refresh_worktree() {
  local db=$2 build=$3 primary what cmd on_failure seed='' dump='' empty=false build_failed=false
  fw::context "$1"
  if [[ "$FW_IS_PRIMARY" == true ]]; then
    fw::die 'Run fire-worktree-refresh in a linked Git worktree, not the primary checkout.'
  fi
  cd "$FW_ROOT" || exit 1
  # Without the generated config, DDEV gives this checkout the primary project's
  # name, and a reset would delete the primary checkout's database.
  FW_NAME=$(fw::generated_name "$FW_ROOT")
  primary=$(fw::primary_name)
  if [[ -n "$FW_NAME" && "$FW_NAME" == "$primary" ]]; then
    fw::die "Refusing to replace the database of the primary DDEV project $primary."
  fi
  if [[ -z "$FW_NAME" ]] || ! fw::db_volume_exists "$FW_NAME"; then
    fw::die 'This worktree has no database of its own yet. Run: ddev fire-worktree-start'
  fi

  db=${db:-$(fw::setting "$FW_ROOT" WORKTREE_DB primary)}
  # Check settings before asking, and stop on errors even where set -e is off,
  # since what follows deletes the database.
  on_failure=$(fw::build_failure "$FW_ROOT") || exit 1
  case $db in
    primary) what="a new copy of the $primary database" ;;
    latest) what="the last copy a worktree took of the $primary database" ;;
    fresh) what='an empty database' ;;
    *) what=$db ;;
  esac
  cmd=$(fw::build_command "$FW_ROOT")
  echo 'This will:'
  echo "  - Delete the database of DDEV project $FW_NAME. To keep a copy, cancel and run ddev snapshot."
  echo "  - Replace it with $what. Other volumes, such as search indexes, are kept."
  if [[ "$build" == true && "$cmd" != none && "$db" != fresh ]]; then
    echo "  - Run $cmd."
  fi
  fw::confirm "$4"

  fw::lock
  seed=$(fw::seed_snapshot "$db") || exit 1
  if [[ -n "$seed" ]] && fw::is_dump "$seed"; then
    dump=$seed
    seed=
  fi
  fw::record_db "$db" "${seed:-$dump}"
  if [[ -n "$seed" ]]; then
    printf 'Seeding the new database from %s\n' "$seed"
  fi
  # Name the project rather than relying on the directory, which DDEV resolves
  # to the primary project when a nested worktree isn't registered.
  ddev start --reset-database --omit-snapshot --skip-confirmation ${seed:+"--seed-snapshot=$seed"} "$FW_NAME" ||
    fw::die "ddev start failed, and the worktree's database may be empty. Fix the error, then run: ddev fire-worktree-refresh --db=$db"
  fw::unlock
  fw::import_dump "$dump"

  if [[ -n "$seed" || -n "$dump" ]]; then
    fw::build_after_copy "$build" || build_failed=true
  else
    empty=true
  fi
  fw::show_worktree "$empty"
  if [[ "$build_failed" == true ]]; then
    fw::build_failed "$on_failure"
  fi
}
